import { test, expect } from '@playwright/test';
import { openMenu } from './menu';

test('developer keys: register, test, revoke without leaking the secret; staff never see the panel', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByLabel('계정', { exact: true }).fill('developer');
  await page.getByLabel('비밀번호', { exact: true }).fill('Browser-test-only-42');
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await openMenu(page, '개발 설정');
  const panel = page.locator('.developer-settings');
  await expect(panel.getByRole('heading', { name: '공급자 키 관리' })).toBeVisible();
  await expect(panel.getByLabel('단계 프롬프트')).toHaveCount(0);
  await panel.getByLabel('키 공급자').selectOption('gemini');
  const secret = 'synthetic-browser-m5-not-a-real-key';
  await panel.getByLabel('Gemini 주키 API 키').fill(secret);
  await panel.getByRole('button', { name: '주키 등록·교체', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Gemini 주키를 보호하여 저장했습니다.' })).toBeVisible();
  await expect(panel.getByLabel('Gemini 주키 API 키')).toHaveValue('');
  await expect(panel.getByRole('region', { name: 'Gemini 주키', exact: true }).getByText('앱에 등록됨', { exact: true })).toBeVisible();
  expect(await page.locator('body').innerText()).not.toContain(secret);
  expect(await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))).not.toContain(secret);
  expect(await (await page.request.get('/api/developer/settings')).text()).not.toContain(secret);
  const state = await (await page.request.get('/api/developer/settings')).json();
  const reference = state.gemini_slots.find((slot: { slot: string }) => slot.slot === 'primary').reference;
  await page.route('**/api/developer/keys/gemini/slots/primary/test', route => route.fulfill({ json: { provider: 'gemini', slot: 'primary', reference, status: 'connected', tested_at: new Date().toISOString() } }));
  await panel.getByRole('button', { name: '주키 연결 시험', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Gemini 주키 연결 시험: 연결 확인' })).toBeVisible();
  await panel.getByRole('button', { name: '주키를 앱에서 제거', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Gemini 주키를 앱에서 제거했습니다.' })).toBeVisible();
  await panel.getByLabel('키 공급자').selectOption('openai');
  await panel.getByLabel('새 API 키').fill('synthetic-openai-ui');
  await panel.getByRole('button', { name: '키 등록·교체', exact: true }).click();
  await expect(panel.getByText('openai · 등록됨', { exact: true })).toBeVisible();
  await panel.getByRole('button', { name: '선택 공급자 키 폐기', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: '키를 폐기했습니다.' })).toBeVisible();
  await panel.getByLabel('키 공급자').selectOption('gemini');
  await panel.screenshot({ path: testInfo.outputPath('keys-desktop.png') });
  await page.setViewportSize({ width: 360, height: 800 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const unsent = 'synthetic-unsent-key-only';
  const input = panel.getByLabel('Gemini 주키 API 키');
  await input.focus(); await input.press('Tab');
  await expect(panel.getByRole('button', { name: '주키 등록·교체', exact: true })).toBeFocused();
  await input.fill(unsent);
  await openMenu(page, '참가자 접수');
  await expect(input).toHaveCount(0);
  await openMenu(page, '개발 설정'); await expect(input).toHaveValue('');
  await input.fill(unsent);
  await page.getByRole('button', { name: '로그아웃' }).click();
  await expect(input).toHaveCount(0);
  await page.getByLabel('계정', { exact: true }).fill('developer');
  await page.getByLabel('비밀번호', { exact: true }).fill('Browser-test-only-42');
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await openMenu(page, '개발 설정'); await expect(input).toHaveValue('');
  await input.fill(unsent);
  await page.request.post('/api/auth/logout', { headers: { 'X-KDOG-Request': '1' } });
  await panel.getByRole('button', { name: '예비키 연결 시험', exact: true }).click();
  await expect(page.getByRole('button', { name: '로그인', exact: true })).toBeVisible();
  await expect(input).toHaveCount(0);
  expect(await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))).not.toContain(unsent);
  await page.getByLabel('계정', { exact: true }).fill('operator');
  await page.getByLabel('비밀번호', { exact: true }).fill('Browser-test-only-42');
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await expect(page.getByRole('button', { name: '로그아웃' })).toBeVisible();
  await expect(page.getByLabel('Gemini 주키 API 키')).toHaveCount(0);
  expect((await page.request.get('/api/developer/settings')).status()).toBe(403);
  expect(errors).toEqual([]);
});
